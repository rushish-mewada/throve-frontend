export function getProductByHandle(handle) {
  if (!handle) return LAUNCH_PRODUCTS[0];
  const normalized = handle.toLowerCase();
  const found = LAUNCH_PRODUCTS.find((p) => p.handle === normalized);
  return found || LAUNCH_PRODUCTS[0];
}

export function getProductsByCategory(category) {
  if (!category || category.toLowerCase() === 'all') return LAUNCH_PRODUCTS;
  return LAUNCH_PRODUCTS.filter(
    (p) => p.category.toLowerCase() === category.toLowerCase()
  );
}

